// The two version stamps (hard rule 9: both versions on every release —
// the tag, the -X stamps, and the Release notes never diverge; one CI step
// derives all three). Overridden at build time:
//
//	wails build -platform windows/amd64 -ldflags \
//	  "-s -w -X main.Version=0.1.4 -X main.WebRef=e6661c8"
var (
	Version = "0.1.5-dev"
	WebRef  = "unpinned"
)

// The island: a checksum-pinned snapshot of the web /kanban board surface,
// synced from hibana-source at WebRef by scripts/sync-island.mjs — NEVER
// hand-edited (the drift check fails CI on any byte).
//
//go:embed all:frontend/dist
var assets embed.FS

// canonical development constants (contract §6: both hosts serve the
// identical app; the desktop presents the canonical origin on writes).
const (
	defaultBaseURL = "https://hibana.ir"
	appDirName     = "hibana"
	pullEvery      = 5 * time.Minute // contract §10: on focus + every 5 min + manual
)

// appCtxVal holds the Wails runtime context (set by OnStartup) so the
// auth-lost emitter can EventsEmit from any goroutine. atomic because the
// sync loop can hit a 401 before the window finishes starting.
var appCtxVal atomic.Value // context.Context

// The close-to-tray state (S214 — "minimize to taskbar"):
//   - hideOnClose is the user's persisted preference (mirror meta table,
//     tray.MetaKey; missing → ON — the owner asked for the behavior, so a
//     missing row must never silently turn the X into quit);
//   - quitRequested is the bypass flag the tray's "Quit Hibana" sets so
//     OnBeforeClose lets the REAL exit through (runtime.Quit routes through
//     OnBeforeClose too — wails' Frontend.Quit consults it on every path).
var (
	hideOnClose   atomic.Bool
	quitRequested atomic.Bool
)

// showWindow restores the board window from any state — hidden to tray,
// minimized — on whatever thread the caller is on (winc's Hide/Show are
// plain ShowWindow syscalls, no marshaling; safe from the tray's thread).
func showWindow() {
	if c, ok := appCtxVal.Load().(context.Context); ok {
		wailsruntime.WindowShow(c)
		wailsruntime.WindowUnminimise(c)
	}
}

func main() {
	dataDir, err := resolveDataDir()
	if err != nil {
		log.Fatalf("hibana: data dir: %v", err)
	}
	if err := os.MkdirAll(dataDir, 0o755); err != nil {
		log.Fatalf("hibana: creating data dir %s: %v", dataDir, err)
	}
	logsDir := filepath.Join(dataDir, "logs")
	_ = os.MkdirAll(logsDir, 0o755)
	logFile, err := os.OpenFile(filepath.Join(logsDir, "hibana.log"), os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o600)
	if err != nil {
		log.Printf("hibana: log file unavailable (%v) — logging to stderr only", err)
	} else {
		log.SetOutput(logFile)
		defer logFile.Close()
	}
	log.Printf("hibana %s (island pin %s), data dir %s", Version, WebRef, dataDir)

	// The cloud client — cookie jar, Origin stamping on writes (the T6 gate),
	// the ETag store; credentials NEVER cross the bridge except the §5.5
	// login round-trip (the cookie itself always stays Go-side).
	client, err := api.New(defaultBaseURL)
	if err != nil {
		log.Fatalf("hibana: %v", err)
	}

	// The SQLite mirror (modernc.org/sqlite — pure Go, no cgo; WAL +
	// foreign_keys per the proven Node adapter, DATA-MODEL §6).
	mirror, err := store.Open(filepath.Join(dataDir, "mirror.db"))
	if err != nil {
		log.Fatalf("hibana: mirror: %v", err)
	}
	defer mirror.Close()

	// Session restore (guide §5.5): a live stored session boots straight
	// into the board; a missing/dead one leaves the login card up — the
	// island's own "can't open" error state stays hidden behind the card
	// until the user signs in.
	sessStore := &auth.FileStore{Path: filepath.Join(dataDir, "session.bin")}
	ctx0 := context.Background()
	me, live, err := auth.Restore(ctx0, client, sessStore)
	if err != nil {
		log.Printf("hibana: session restore: %v", err)
	}
	if live {
		log.Printf("hibana: session restored (%s)", me.User.Email)
	} else {
		log.Printf("hibana: no live session — the login card opens")
	}

	engine := sync.New(client, mirror)
	syncCtx, syncCancel := context.WithCancel(ctx0)
	defer syncCancel()

	// THE THEME PREFERENCE (S216 — v0.1.5): the mirror meta row is the ONE
	// source of truth ('light' | 'claude-dark' | 'system'; default system —
	// the web's own S87 default; a missing/garbage row reads as system).
	// The seed paints the boot frame BEFORE the WebView exists and serves
	// on <html> with every document (InjectShellState) — a ZERO-JS first
	// paint in either look.
	bootTheme := ui.ThemeSystem
	if v, _, err := mirror.GetMeta(ctx0, ui.ThemeMetaKey); err != nil {
		log.Printf("hibana: theme preference read: %v (defaulting to system)", err)
	} else {
		bootTheme = ui.NormalizeTheme(v)
	}

	// The bridge: the transport + the §5.5 login surface + the boot snapshot
	// the served index.html carries (first-paint card visibility).
	bridge := ui.New(client, Version, WebRef)
	bridge.SetSessionStore(sessStore)
	bridge.SetAuthed(me, live)
	bridge.SetThemeSeed(bootTheme)
	// The persist hook writes the meta row; a failure is logged inside
	// SetTheme and NEVER fails the flip (the live document already
	// changed — the next boot re-reads the last persisted value).
	bridge.SetThemePersist(func(pref string) error {
		return mirror.SetMeta(context.Background(), ui.ThemeMetaKey, pref)
	})
	// The change hook flips the LIVE document without a reload (the tray
	// menu's Light / Dark / Follow system picker rides the same path the
	// island's two toggles use — js/desktop-theme.js listens).
	bridge.SetThemeChange(func(pref string) {
		log.Printf("hibana: theme → %s", pref)
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, "hibana:theme", map[string]string{"pref": pref})
		}
	})
	bridge.SetOnLogin(func(u *api.MeUser) {
		log.Printf("hibana: signed in as %s — pulling boards", u.Email)
		go func() {
			pulled, errs := engine.SyncOnce(syncCtx)
			for _, e := range errs {
				log.Printf("hibana sync: %v", e)
			}
			log.Printf("hibana sync: post-login pull done (boards pulled: %d)", pulled)
		}()
	})
	bridge.SetOnAuthLost(func(reason string) {
		log.Printf("hibana: session lost (%s) — reopening the login card", reason)
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, "hibana:auth-required", reason)
		}
	})
	// The outbox's 401 rule (§10): re-auth (the card), then retry the op
	// once when the user signs back in.
	engine.SetRelogin(func(ctx context.Context) error {
		bridge.NotifyAuthLost("outbox-401")
		return bridge.AwaitRelogin(ctx)
	})

	// The first sync-loop milestone: pull on startup, then every 5 minutes
	// (the on-focus + manual triggers join with the M2 shell events). The
	// outbox drain rides the same tick — FIFO, one in-flight, §10.
	go syncLoop(syncCtx, engine, bridge)

	// The S214 tray — the "minimize to taskbar" option: the Hibana icon
	// sits in the notification area the whole session; left-click
	// restores, right-click offers Open / the close-to-tray toggle / Quit.
	// The preference rides the mirror's meta table (default ON). A failed
	// tray is survivable but then the X must QUIT — otherwise a hidden
	// window with no icon to bring it back would strand the app.
	if v, ok, err := mirror.GetMeta(ctx0, tray.MetaKey); err != nil {
		log.Printf("hibana: tray preference read: %v (defaulting on)", err)
	} else {
		hideOnClose.Store(tray.HideOnCloseFromMeta(v, ok))
	}
	go func() {
		err := tray.Run(tray.Config{
			Icon:      trayIconICO,
			Tooltip:   "Hibana Kanban — running",
			IsOn:      hideOnClose.Load,
			OnShow:    showWindow,
			ThemePref: bridge.ThemePref,
			OnTheme: func(pref string) {
				// The tray's Theme submenu rides the SAME SetTheme path —
				// validate + persist + emit; a garbage id can never land here
				// (commandThemePref is a pure allow-list map), and a rejected
				// flip logs — the live look is never left dangling.
				if _, err := bridge.SetTheme(pref); err != nil {
					log.Printf("hibana: tray theme %q rejected: %v", pref, err)
				}
			},
			OnToggle: func(on bool) {
				hideOnClose.Store(on)
				v := "0"
				if on {
					v = "1"
				}
				if err := mirror.SetMeta(context.Background(), tray.MetaKey, v); err != nil {
					log.Printf("hibana: persisting hide-on-close=%v failed: %v", on, err)
				}
				state := "off — close button quits"
				if on {
					state = "on — close button hides to the tray"
				}
				log.Printf("hibana: hide-on-close %s", state)
			},
			OnQuit: func() {
				quitRequested.Store(true) // OnBeforeClose must let the real exit through
				if c, ok := appCtxVal.Load().(context.Context); ok {
					wailsruntime.Quit(c)
				}
			},
		})
		if err != nil {
			log.Printf("hibana: tray unavailable (%v) — close button quits", err)
			hideOnClose.Store(false) // NEVER strand a hidden window behind a dead tray
		}
	}()

	err = wails.Run(&options.App{
		Title:     "Hibana Kanban",
		Width:     1600,
		Height:    900,
		MinWidth:  1100, // the board's 5-column grid breakpoint (UI-UX §2)
		MinHeight: 720,
		// The boot frame paints the RESOLVED look (#141413 dark /
		// #E7E7E7 light — themes.css's own --bg tokens) so a dark-mode
		// OS never flashes white before the island loads (S216).
		BackgroundColour: func() *options.RGBA { bg := resolveBootBackground(bootTheme); return &bg }(),
		OnStartup: func(ctx context.Context) {
			appCtxVal.Store(ctx)
		},
		OnShutdown: func(context.Context) {
			tray.Stop() // NIM_DELETE + quit the tray's message loop
		},
		// The close button contract (S214): with the preference ON
		// (default) the X hides the window to the tray — the app keeps
		// running, the sync loop keeps pulling; the tray icon (or a
		// second exe launch) brings it back. The tray's Quit sets
		// quitRequested so the REAL exit passes. Preference OFF → X
		// quits. WindowHide here is a plain ShowWindow(SW_HIDE)
		// syscall (winc), safe to call from this main-thread callback.
		OnBeforeClose: func(context.Context) bool {
			if quitRequested.Load() {
				return false
			}
			if !hideOnClose.Load() {
				return false
			}
			log.Printf("hibana: close → tray (hide-on-close on; quit via the tray menu)")
			if c, ok := appCtxVal.Load().(context.Context); ok {
				wailsruntime.WindowHide(c)
			}
			return true // prevent the quit; the window is gone from the taskbar
		},
		SingleInstanceLock: &options.SingleInstanceLock{
			UniqueId: "hibana-kanban-desktop",
			OnSecondInstanceLaunch: func(secondInstanceData options.SecondInstanceData) {
				// Second launch focuses THIS window — even from the tray: the
				// close-to-tray recovery path when the user forgets the icon.
				log.Printf("hibana: second instance launched (%v) — showing this one", secondInstanceData.Args)
				showWindow()
			},
		},
		AssetServer: &assetserver.Options{
			Assets: assets,
			// The canonical entry contract: the island IS /kanban (board-page.js
			// resolves the entry state from location.pathname — isKanbanEntry()
			// board-page.js:28 — so the asset server aliases the route exactly
			// like the Worker does (app.ts:370-385). A bare "/" boot bounces
			// once via the island's own guard (:29) — by design, so the deep
			// link state matches the web app byte-for-byte.
			//
			// TWO document lanes (the v0.1.0/v0.1.1 dogfood lesson — ONE root
			// cause, fixed in v0.1.2): Wails injects its runtime scripts
			// (ipc.js + runtime.js — the window.go bindings) ONLY into
			// "/"-suffix documents (assetserver.isRuntimeInjectionMatch), but
			// the island's guard lands the WebView on /kanban, where they are
			// never injected — window.go was missing on the page the user
			// actually sees and every bridge call died with "bridge not wired".
			// The aliased document therefore carries the runtime tags itself
			// (KanbanIndexMiddleware); the true "/" keeps Wails' own injection.
			// Both lanes put the live auth state on the <html> tag (the login
			// card's visibility is a first-paint CSS decision, never a JS
			// flash).
			Middleware: func(next http.Handler) http.Handler {
				root := bridge.IndexMiddleware(next)
				kanban := bridge.KanbanIndexMiddleware(next)
				return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					if p := r.URL.Path; p == "/kanban" || p == "/kanban.html" || p == "/board.html" {
						r.URL.Path = "/"
						kanban.ServeHTTP(w, r)
						return
					}
					root.ServeHTTP(w, r)
				})
			},
		},
		Bind: []interface{}{bridge},
		Windows: &windows.Options{
			WebviewIsTransparent: false,
			WindowIsTranslucent:  false,
		},
	})
	if err != nil {
		log.Fatalf("hibana: wails: %v", err)
	}
}

// syncLoop is the pull cadence (§10): startup + every 5 minutes; each round
// refreshes the projects list, pulls every mirrored board (304s are one
// header), and drains the outbox when it has entries. A 401 anywhere in the
// round means the session died: the bridge is notified (the login card
// reopens); the next round after a re-login recovers on its own.
func syncLoop(ctx context.Context, engine *sync.Engine, bridge *ui.API) {
	round := func() {
		pulled, errs := engine.SyncOnce(ctx)
		for _, err := range errs {
			var se *api.StatusError
			if errors.As(err, &se) && se.Status == http.StatusUnauthorized {
				bridge.NotifyAuthLost("pull-401")
			}
			log.Printf("hibana sync: %v", err)
		}
		res, err := engine.Drain(ctx)
		if err != nil {
			log.Printf("hibana sync: drain: %v", err)
		}
		if res.Done > 0 || res.Dropped > 0 || res.Held > 0 {
			log.Printf("hibana sync: round done (boards pulled: %d, outbox done/dropped/held: %d/%d/%d)", pulled, res.Done, res.Dropped, res.Held)
		}
	}
	round() // startup pull
	t := time.NewTicker(pullEvery)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			round()
		}
	}
}

// resolveDataDir implements the never-mix data rule (WPP §1): portable mode
// is chosen by --portable OR a zero-byte portable.marker next to the exe →
// .\data\; otherwise the OS data dir (%LOCALAPPDATA%\hibana\ on Windows).
// The choice locks into mode.lock on first launch and the lock WINS on every
// later launch — the app never silently migrates between profiles.
func resolveDataDir() (string, error) {
	exe, err := os.Executable()
	if err != nil {
		return "", err
	}
	exeDir := filepath.Dir(exe)
	portableFlag := false
	for _, a := range os.Args[1:] {
		if a == "--portable" {
			portableFlag = true
		}
	}
	_, markerErr := os.Stat(filepath.Join(exeDir, "portable.marker"))
	portableNow := portableFlag || markerErr == nil

	osDir := os.UserConfigDir // %LOCALAPPDATA% on Windows, ~/.config elsewhere
	if runtime.GOOS == "windows" {
		// WPP §8: %LOCALAPPDATA%\hibana\ (the plan's canonical installed path).
		if la := os.Getenv("LOCALAPPDATA"); la != "" {
			osDir = func() (string, error) { return filepath.Join(la, appDirName), nil }
		}
	}

	installedDir := func() (string, error) {
		base, err := osDir()
		if err != nil {
			return "", err
		}
		if runtime.GOOS == "windows" {
			return filepath.Join(base, appDirName), nil
		}
		return filepath.Join(base, appDirName), nil
	}

	lockPath := ""
	candidate := ""
	if portableNow {
		candidate = filepath.Join(exeDir, "data")
		lockPath = filepath.Join(candidate, "mode.lock")
	} else {
		d, err := installedDir()
		if err != nil {
			return "", err
		}
		candidate = d
		lockPath = filepath.Join(candidate, "mode.lock")
	}
	if err := os.MkdirAll(candidate, 0o755); err != nil {
		return "", err
	}

	// The lock wins: a recorded choice is never silently overridden.
	if b, err := os.ReadFile(lockPath); err == nil {
		switch strings.TrimSpace(string(b)) {
		case "portable":
			return filepath.Join(exeDir, "data"), nil
		case "installed":
			return installedDir()
		}
	}
	mode := "installed"
	if portableNow {
		mode = "portable"
	}
	if err := os.WriteFile(lockPath, []byte(mode), 0o600); err != nil {
		return "", err
	}
	return candidate, nil
}
