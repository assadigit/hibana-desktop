// appCtxVal holds the Wails runtime context (set by OnStartup) so the
// auth-lost emitter can EventsEmit from any goroutine. atomic because the
// sync loop can hit a 401 before the window finishes starting.
var appCtxVal atomic.Value // context.Context

// The close-to-tray state (S214 — "minimize to taskbar"):
//   - hideOnClose is the user's persisted preference (mirror meta table,
//     tray.MetaKey; missing → ON — the owner asked for the behavior, so a
//     missing row must never silently turn the X into quit);
//   - quitRequested is the bypass flag the tray's "Quit Hibana" sets so
//     OnBeforeClose lets the REAL exit through (runtime.Quit routes through
//     OnBeforeClose too — wails' Frontend.Quit consults it on every path).
var (
	hideOnClose   atomic.Bool
	quitRequested atomic.Bool
)

// THE QUICK-ACCESS ROUND (the owner's taskbar ask): the boot flag the
// Startup shortcut passes (quickaccess.AutostartFlag). A boot with it starts
// the window HIDDEN — the tray icon is the visible presence (one left-click
// and the board is back), exactly the tray-first contract every background
// app ships; a manual launch (Start Menu, pinned taskbar, the exe itself)
// carries no flag and opens the board as always. Parsed BEFORE any side
// effect so it is testable (main_test.go).
func hasAutostartFlag(args []string) bool {
	for _, a := range args {
		if a == quickaccess.AutostartFlag {
			return true
		}
	}
	return false
}

// startupPreference reads the persisted start-with-Windows preference
// (the mirror meta row; missing/garbage = ON — the owner's "must have an
// automatic appearance" is the default, so only an explicit opt-out counts).
const startupMetaKey = "ui.start_with_windows"

func startupPreference(v string, ok bool) bool { return !(ok && v == "0") }

// showWindow restores the board window from any state — hidden to tray,
// minimized — on whatever thread the caller is on (winc's Hide/Show are
// plain ShowWindow syscalls, no marshaling; safe from the tray's thread).
func showWindow() {
	if c, ok := appCtxVal.Load().(context.Context); ok {
		wailsruntime.WindowShow(c)
		wailsruntime.WindowUnminimise(c)
	}
}

// S222 — THE MERGED CHROME (the owner ask: "make the edge of app rounded and
// modern" — the title-bar half; the rounded-corners half lives in
// edge_windows.go): the native title bar, its text, and the window border
// hairline paint the ISLAND'S OWN tokens instead of the OS scheme du jour —
// the dark app wears the #141413 bar with #EDEDEC ink (claude-dark-theme.css
// --bg/--text), the light app #E7E7E7 with #141414 (themes.css) — so the
// chrome visually MERGES with the toolbar below it instead of the old
// OS-white strip floating over a dark app.
//
// Ridden through wails' own Windows theme path: SetTheme → UpdateTheme →
// immersive dark mode (Win10 1809+ — the dark bar survives there) plus the
// CustomTheme colors (DWMWA_CAPTION_COLOR/_TEXT_COLOR/_BORDER_COLOR,
// Win11 22000+). 'system' maps to wails' SystemDefault, and the wails
// window ALREADY watches WM_SETTINGCHANGE "ImmersiveColorSet" (its own
// window.go), so OS flips while the pref is 'system' re-resolve natively —
// zero extra code on this side for that path.
type windowChromeTheme int

const (
	chromeFollowsSystem windowChromeTheme = iota
	chromeLight
	chromeDark
)

// chromeThemeFor is the pure pref→chrome map (main_test.go): callers pass
// ALREADY-NORMALIZED preferences (ui.NormalizeTheme output — the boot read,
// the SetTheme binding, the change hook), so the legacy 'dark' alias and
// garbage land on 'system' here by contract, exactly like every other
// unreadable value.
func chromeThemeFor(pref string) windowChromeTheme {
	switch pref {
	case ui.ThemeDark:
		return chromeDark
	case ui.ThemeLight:
		return chromeLight
	default: // 'system' + anything unreadable
		return chromeFollowsSystem
	}
}

// bootWindowTheme seeds the wails window Theme at creation (the options
// block runs BEFORE wails.Run, where bootTheme is already resolved) — the
// chrome is right from the very first frame, no flash of the OS-scheme bar.
func bootWindowTheme(pref string) windows.Theme {
	switch chromeThemeFor(pref) {
	case chromeDark:
		return windows.Dark
	case chromeLight:
		return windows.Light
	default:
		return windows.SystemDefault
	}
}

// applyWindowThemeChrome pushes a live theme flip into the wails window
// (the island toggle surfaces' SetTheme binding → the change hook → here,
// and the tray's Theme submenu rides the same path). Safe from any
// goroutine — wails' SetTheme Invoke-marshals onto the main thread; a
// pre-startup call (no ctx yet) no-ops, and the creation-time seed already
// painted the right chrome anyway.
func applyWindowThemeChrome(pref string) {
	c, ok := appCtxVal.Load().(context.Context)
	if !ok {
		return
	}
	switch chromeThemeFor(pref) {
	case chromeDark:
		wailsruntime.WindowSetDarkTheme(c)
	case chromeLight:
		wailsruntime.WindowSetLightTheme(c)
	default:
		wailsruntime.WindowSetSystemDefaultTheme(c)
	}
}

func main() {
	dataDir, err := resolveDataDir()
	if err != nil {
		log.Fatalf("hibana: data dir: %v", err)
	}
	if err := os.MkdirAll(dataDir, 0o755); err != nil {
		log.Fatalf("hibana: creating data dir %s: %v", dataDir, err)
	}
	logsDir := filepath.Join(dataDir, "logs")
	_ = os.MkdirAll(logsDir, 0o755)
	logFile, err := os.OpenFile(filepath.Join(logsDir, "hibana.log"), os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o600)
	if err != nil {
		log.Printf("hibana: log file unavailable (%v) — logging to stderr only", err)
	} else {
		log.SetOutput(logFile)
		defer logFile.Close()
	}
	log.Printf("hibana %s (island pin %s), data dir %s", Version, WebRef, dataDir)

	// THE QUICK-ACCESS BOOT (the owner's taskbar ask): the flag the
	// Startup shortcut passes — the window boots HIDDEN and the tray
	// icon is the presence (a manual launch never carries it).
	bootHidden := hasAutostartFlag(os.Args[1:])
	if bootHidden {
		log.Printf("hibana: autostart boot — starting hidden to the tray (left-click the icon to open the board)")
	}

	// The cloud client — cookie jar, Origin stamping on writes (the T6 gate),
	// the ETag store; credentials NEVER cross the bridge except the §5.5
	// login round-trip (the cookie itself always stays Go-side).
	client, err := api.New(defaultBaseURL)
	if err != nil {
		log.Fatalf("hibana: %v", err)
	}

	// The SQLite mirror (modernc.org/sqlite — pure Go, no cgo; WAL +
	// foreign_keys per the proven Node adapter, DATA-MODEL §6).
	mirror, err := store.Open(filepath.Join(dataDir, "mirror.db"))
	if err != nil {
		log.Fatalf("hibana: mirror: %v", err)
	}
	defer mirror.Close()

	// Session restore (guide §5.5): a live stored session boots straight
	// into the board; a missing/dead one leaves the login card up — the
	// island's own "can't open" error state stays hidden behind the card
	// until the user signs in.
	sessStore := &auth.FileStore{Path: filepath.Join(dataDir, "session.bin")}
	ctx0 := context.Background()
	me, live, err := auth.Restore(ctx0, client, sessStore)
	if err != nil {
		log.Printf("hibana: session restore: %v", err)
	}
	if live {
		log.Printf("hibana: session restored (%s)", me.User.Email)
	} else {
		log.Printf("hibana: no live session — the login card opens")
	}

	engine := sync.New(client, mirror)
	syncCtx, syncCancel := context.WithCancel(ctx0)
	defer syncCancel()

	// THE QUICK-ACCESS WIRING (the owner's taskbar ask): the persisted
	// start-with-Windows preference (default ON — "must have an automatic
	// appearance"; only an explicit opt-out counts) drives the Startup
	// shortcut + the tray toggle's check state. The shortcut pair
	// (Start Menu + Startup) writes itself in a goroutine — idempotent,
	// quiet on every later boot (the marker in the data dir matches),
	// NEVER blocking the window: a slow COM spin is machinery.
	startWithWindows := true
	if v, ok, err := mirror.GetMeta(ctx0, startupMetaKey); err != nil {
		log.Printf("hibana: start-with-Windows preference read: %v (defaulting on)", err)
	} else {
		startWithWindows = startupPreference(v, ok)
	}
	exePath, exeErr := os.Executable()
	if exeErr != nil {
		log.Printf("hibana: resolving the exe path for quick access: %v", exeErr)
	} else {
		go func() {
			if err := quickaccess.Ensure(exePath, dataDir, startWithWindows); err != nil {
				log.Printf("hibana: quick access (Start Menu + Startup shortcuts): %v", err)
			} else {
				state := "off"
				if startWithWindows {
					state = "on"
				}
				log.Printf("hibana: quick access ensured — Start Menu shortcut present, start with Windows %s", state)
			}
		}()
	}

	// THE THEME PREFERENCE (S216 — v0.1.5): the mirror meta row is the ONE
	// source of truth ('light' | 'claude-dark' | 'system'; default system —
	// the web's own S87 default; a missing/garbage row reads as system).
	// The seed paints the boot frame BEFORE the WebView exists and serves
	// on <html> with every document (InjectShellState) — a ZERO-JS first
	// paint in either look.
	bootTheme := ui.ThemeSystem
	if v, _, err := mirror.GetMeta(ctx0, ui.ThemeMetaKey); err != nil {
		log.Printf("hibana: theme preference read: %v (defaulting to system)", err)
	} else {
		bootTheme = ui.NormalizeTheme(v)
	}

	// The bridge: the transport + the §5.5 login surface + the boot snapshot
	// the served index.html carries (first-paint card visibility).
	bridge := ui.New(client, Version, WebRef)
	bridge.SetSessionStore(sessStore)
	bridge.SetAuthed(me, live)
	bridge.SetThemeSeed(bootTheme)
	// The persist hook writes the meta row; a failure is logged inside
	// SetTheme and NEVER fails the flip (the live document already
	// changed — the next boot re-reads the last persisted value).
	bridge.SetThemePersist(func(pref string) error {
		return mirror.SetMeta(context.Background(), ui.ThemeMetaKey, pref)
	})
	// The change hook flips the LIVE document without a reload (the tray
	// menu's Light / Dark / Follow system picker rides the same path the
	// island's two toggles use — js/desktop-theme.js listens).
	bridge.SetThemeChange(func(pref string) {
		log.Printf("hibana: theme → %s", pref)
		applyWindowThemeChrome(pref) // S222: the merged chrome follows every flip (island + tray)
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, "hibana:theme", map[string]string{"pref": pref})
		}
	})
	// THE MANUAL SYNC ROUND (S217 — v0.1.6): the toolbar's physical Sync
	// button → ui.SyncNow → engine.SyncRound, every transition relayed to
	// the modal live (js/desktop-sync.js paints the step rows). A session
	// outcome reopens the login card ABOVE the modal (NotifyAuthLost) so a
	// re-login recovers without dismissing the proof.
	bridge.SetSyncEmit(func(step, state, detail string) {
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, "hibana:sync-progress", map[string]string{"step": step, "state": state, "detail": detail})
		}
	})
	// THE UPLOAD ROUND (the owner's dogfood: "it doesn't show whether it
	// was successful or not"): the progress relay the shim's XHR proxy
	// routes to the uploader's per-file bars — REAL bytes-in-flight from
	// the streaming write (ui.Upload → client.WriteStream).
	bridge.SetUploadEmit(func(name string, payload map[string]any) {
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, name, payload)
		}
	})
	bridge.SetSyncRun(func(ctx context.Context, emit sync.Emit) (sync.RoundOutcome, error) {
		out, err := engine.SyncRound(ctx, emit)
		if out.Code == sync.OutcomeSession {
			bridge.NotifyAuthLost("sync-session")
		}
		return out, err
	})
	bridge.SetOnLogin(func(u *api.MeUser) {
		log.Printf("hibana: signed in as %s — pulling boards", u.Email)
		go func() {
			pulled, errs := engine.SyncOnce(syncCtx)
			for _, e := range errs {
				log.Printf("hibana sync: %v", e)
			}
			log.Printf("hibana sync: post-login pull done (boards pulled: %d)", pulled)
		}()
	})
	bridge.SetOnAuthLost(func(reason string) {
		log.Printf("hibana: session lost (%s) — reopening the login card", reason)
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, "hibana:auth-required", reason)
		}
	})
	// THE SIGN-OUT PATH (v0.1.9 — the owner ask: "option of logout and
	// enter with a new account"): the toolbar's Log out button → the
	// confirm dialog → ui.Logout, which calls this hook after the cookie,
	// the session file and the ETag cache are already gone. The wipe
	// clears the mirror's account-scoped rows + the pull cursors; the
	// DEVICE-scope rows survive a sign-out (the light/dark theme and the
	// close-to-tray preference are machine settings, not account data).
	bridge.SetOnLogout(func() error {
		return mirror.ResetAccount(context.Background(), ui.ThemeMetaKey, tray.MetaKey)
	})
	// The outbox's 401 rule (§10): re-auth (the card), then retry the op
	// once when the user signs back in.
	engine.SetRelogin(func(ctx context.Context) error {
		bridge.NotifyAuthLost("outbox-401")
		return bridge.AwaitRelogin(ctx)
	})

	// The first sync-loop milestone: pull on startup, then every 5 minutes
	// (the on-focus + manual triggers join with the M2 shell events). The
	// outbox drain rides the same tick — FIFO, one in-flight, §10.
	go syncLoop(syncCtx, engine, bridge)

	// THE AUTO-UPDATE ROUND (v0.1.14 — the owner ask: "Add an auto update for
	// the app. when the new version releases in the github, app syncs with
	// the internet and github, and if new version, whether portable or
	// installer released, show a button for update. it must update from
	// github and replace without losing data or needing user to re login."):
	// the shell owns the Updater — ONE repo, the -X stamped Version, the data
	// dir for staging (the never-mix rule keeps the session + mirror off the
	// replace path, so the restarted exe boots straight back into the board).
	// The check rides the loop below (startup + every 2h); the apply rides
	// the bridge's ApplyUpdate — every phase honest, verified against the
	// release's own checksums.txt before the swap.
	updater := &update.Updater{
		Repo:    "assadigit/hibana-desktop",
		Current: Version,
		DataDir: dataDir,
	}
	bridge.SetUpdateCheck(func(ctx context.Context) (update.CheckResult, error) {
		return updater.Check(ctx)
	})
	bridge.SetUpdateEmit(func(name string, payload map[string]any) {
		if c, ok := appCtxVal.Load().(context.Context); ok {
			wailsruntime.EventsEmit(c, name, payload)
		}
	})
	bridge.SetUpdateApply(func(ctx context.Context, progress func(update.Progress)) (update.ApplyResult, error) {
		// THE PREPARE — download + the checksums chain (the asset AND, for
		// the zip, the hibana.exe entry inside it). A failure resolves as a
		// verdict for the modal's red panel; nothing was applied.
		assetPath, kind, err := updater.Prepare(ctx, progress)
		if err != nil {
			return update.ApplyResult{Message: err.Error()}, nil
		}
		// THE APPLY — the detached helper is spawned (apply_windows.go);
		// it waits for THIS process to exit, swaps the exe, relaunches it.
		if err := updater.Apply(assetPath, kind); err != nil {
			return update.ApplyResult{Message: err.Error()}, nil
		}
		// THE RESTART — the modal paints "restarting…" on this {ok:true}
		// resolve; the quit lands a beat later so the message is on screen
		// when the window goes. quitRequested bypasses the close-to-tray
		// contract (an update restart must QUIT, never hide — the helper
		// would wait forever on a hidden-but-alive process).
		go func() {
			time.Sleep(1500 * time.Millisecond)
			log.Printf("hibana: update to %s staged + helper spawned — restarting", updater.LastVersion)
			quitRequested.Store(true)
			if c, ok := appCtxVal.Load().(context.Context); ok {
				wailsruntime.Quit(c)
			}
		}()
		return update.ApplyResult{OK: true}, nil
	})
	go updateLoop(ctx0, bridge)

	// The S214 tray — the "minimize to taskbar" option: the Hibana icon
	// sits in the notification area the whole session; left-click
	// restores, right-click offers Open / the close-to-tray toggle / Quit.
	// The preference rides the mirror's meta table (default ON). A failed
	// tray is survivable but then the X must QUIT — otherwise a hidden
	// window with no icon to bring it back would strand the app.
	if v, ok, err := mirror.GetMeta(ctx0, tray.MetaKey); err != nil {
		log.Printf("hibana: tray preference read: %v (defaulting on)", err)
	} else {
		hideOnClose.Store(tray.HideOnCloseFromMeta(v, ok))
	}
	startWithWin := &atomic.Bool{}
	startWithWin.Store(startWithWindows)
	go func() {
		err := tray.Run(tray.Config{
			Icon:      trayIconICO,
			Tooltip:   "Hibana Kanban — running",
			IsOn:      hideOnClose.Load,
			OnShow:    showWindow,
			ThemePref: bridge.ThemePref,
			OnTheme: func(pref string) {
				// The tray's Theme submenu rides the SAME SetTheme path —
				// validate + persist + emit; a garbage id can never land here
				// (commandThemePref is a pure allow-list map), and a rejected
				// flip logs — the live look is never left dangling.
				if _, err := bridge.SetTheme(pref); err != nil {
					log.Printf("hibana: tray theme %q rejected: %v", pref, err)
				}
			},
			OnToggle: func(on bool) {
				hideOnClose.Store(on)
				v := "0"
				if on {
					v = "1"
				}
				if err := mirror.SetMeta(context.Background(), tray.MetaKey, v); err != nil {
					log.Printf("hibana: persisting hide-on-close=%v failed: %v", on, err)
				}
				state := "off — close button quits"
				if on {
					state = "on — close button hides to the tray"
				}
				log.Printf("hibana: hide-on-close %s", state)
			},
			StartupIsOn: startWithWin.Load,
			OnStartup: func(on bool) {
				// THE QUICK-ACCESS TOGGLE (the owner's taskbar
				// ask): persist + write/remove the Startup
				// .lnk. The shortcut write is the slow half —
				// it runs on the tray's thread, but it is a
				// one-shot user click, never a boot path.
				v := "0"
				if on {
					v = "1"
				}
				if err := mirror.SetMeta(context.Background(), startupMetaKey, v); err != nil {
					log.Printf("hibana: persisting start-with-Windows=%v failed: %v", on, err)
				}
				startWithWin.Store(on)
				if exeErr == nil {
					if err := quickaccess.SetStartup(on, exePath, dataDir); err != nil {
						log.Printf("hibana: writing the start-with-Windows shortcut failed: %v", err)
					}
				}
				state := "off — launch Hibana from the Start Menu"
				if on {
					state = "on — Hibana starts to the tray with Windows"
				}
				log.Printf("hibana: start with Windows %s", state)
			},
			OnQuit: func() {
				quitRequested.Store(true) // OnBeforeClose must let the real exit through
				if c, ok := appCtxVal.Load().(context.Context); ok {
					wailsruntime.Quit(c)
				}
			},
		})
		if err != nil {
			log.Printf("hibana: tray unavailable (%v) — close button quits", err)
			hideOnClose.Store(false) // NEVER strand a hidden window behind a dead tray
		}
	}()

	err = wails.Run(&options.App{
		Title:     "Hibana Kanban",
		Width:     1600,
		Height:    900,
		MinWidth:  1100, // the board's 5-column grid breakpoint (UI-UX §2)
		MinHeight: 720,
		// THE QUICK-ACCESS BOOT (the owner's taskbar ask): a boot
		// from the Startup shortcut starts HIDDEN — the tray icon is
		// the visible presence (left-click reopens the board), the
		// same tray-first contract the close-to-tray round ships;
		// every manual launch shows the window as always.
		StartHidden: bootHidden,
		// The boot frame paints the RESOLVED look (#141413 dark /
		// #E7E7E7 light — themes.css's own --bg tokens) so a dark-mode
		// OS never flashes white before the island loads (S216).
		BackgroundColour: func() *options.RGBA { bg := resolveBootBackground(bootTheme); return &bg }(),
		OnStartup: func(ctx context.Context) {
			appCtxVal.Store(ctx)
			// S222 — the rounded window edge: the DWM corner pass
			// in its own goroutine (its retry loop sleeps and must
			// never stall this callback or the message loop). The
			// chrome itself needs no call here — the options block
			// seeded the wails window Theme from bootTheme BEFORE
			// wails.Run, so the title bar is right at frame one.
			go applyWindowEdge()
		},
		OnShutdown: func(context.Context) {
			tray.Stop() // NIM_DELETE + quit the tray's message loop
		},
		// The close button contract (S214): with the preference ON
		// (default) the X hides the window to the tray — the app keeps
		// running, the sync loop keeps pulling; the tray icon (or a
		// second exe launch) brings it back. The tray's Quit sets
		// quitRequested so the REAL exit passes. Preference OFF → X
		// quits. WindowHide here is a plain ShowWindow(SW_HIDE)
		// syscall (winc), safe to call from this main-thread callback.
		OnBeforeClose: func(context.Context) bool {
			if quitRequested.Load() {
				return false
			}
			if !hideOnClose.Load() {
				return false
			}
			log.Printf("hibana: close → tray (hide-on-close on; quit via the tray menu)")
			if c, ok := appCtxVal.Load().(context.Context); ok {
				wailsruntime.WindowHide(c)
			}
			return true // prevent the quit; the window is gone from the taskbar
		},
		SingleInstanceLock: &options.SingleInstanceLock{
			UniqueId: "hibana-kanban-desktop",
			OnSecondInstanceLaunch: func(secondInstanceData options.SecondInstanceData) {
				// Second launch focuses THIS window — even from the tray: the
				// close-to-tray recovery path when the user forgets the icon.
				log.Printf("hibana: second instance launched (%v) — showing this one", secondInstanceData.Args)
				showWindow()
			},
		},
		AssetServer: &assetserver.Options{
			Assets: assets,
			// The canonical entry contract: the island IS /kanban (board-page.js
			// resolves the entry state from location.pathname — isKanbanEntry()
			// board-page.js:28 — so the asset server aliases the route exactly
			// like the Worker does (app.ts:370-385). A bare "/" boot bounces
			// once via the island's own guard (:29) — by design, so the deep
			// link state matches the web app byte-for-byte.
			//
			// TWO document lanes (the v0.1.0/v0.1.1 dogfood lesson — ONE root
			// cause, fixed in v0.1.2): Wails injects its runtime scripts
			// (ipc.js + runtime.js — the window.go bindings) ONLY into
			// "/"-suffix documents (assetserver.isRuntimeInjectionMatch), but
			// the island's guard lands the WebView on /kanban, where they are
			// never injected — window.go was missing on the page the user
			// actually sees and every bridge call died with "bridge not wired".
			// The aliased document therefore carries the runtime tags itself
			// (KanbanIndexMiddleware); the true "/" keeps Wails' own injection.
			// Both lanes put the live auth state on the <html> tag (the login
			// card's visibility is a first-paint CSS decision, never a JS
			// flash).
			Middleware: func(next http.Handler) http.Handler {
				// THE MEDIA PROXY (the upload round's thumbnail
				// half): the island loads shot tiles as
				// /api/media/… <img> srcs — on the web those go
				// to the Worker; in the desktop they land HERE
				// on the embedded asset server. Route them
				// through the Go cookie jar first (the media
				// routes are authed), then the document lanes.
				media := bridge.MediaMiddleware(next)
				root := bridge.IndexMiddleware(media)
				kanban := bridge.KanbanIndexMiddleware(media)
				return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					if p := r.URL.Path; p == "/kanban" || p == "/kanban.html" || p == "/board.html" {
						r.URL.Path = "/"
						kanban.ServeHTTP(w, r)
						return
					}
					root.ServeHTTP(w, r)
				})
			},
		},
		Bind: []interface{}{bridge},
		Windows: &windows.Options{
			WebviewIsTransparent: false,
			WindowIsTranslucent:  false,
			// S222 — THE MERGED CHROME, seeded at creation: the
			// wails window is BORN in the stored look (Theme from
			// bootTheme — resolved before wails.Run), so the first
			// frame never wears the OS scheme's bar; live flips
			// ride applyWindowThemeChrome. 'system' stays
			// SystemDefault and the wails window follows OS flips
			// natively (WM_SETTINGCHANGE watcher).
			Theme: bootWindowTheme(bootTheme),
			// The island's own tokens as COLORREFs (0x00BBGGRR),
			// ACTIVE and INACTIVE (wails paints the inactive pair
			// on focus loss) — dark: --bg #141413 bar, --text
			// #EDEDEC ink, --line #34322f hairline; inactive bar
			// --bg-soft #1f1e1c with --muted #9C9C9B ink. light:
			// --bg #E7E7E7 bar, --text #141414 ink, --line #D4D4D4
			// hairline; inactive #DEDEDE with the #5C5C5C ink.
			// (Win11 22000+ paints all of these; Win10 1809+ keeps
			// the immersive dark/light bar from Theme — the color
			// attrs no-op harmlessly there.)
			CustomTheme: &windows.ThemeSettings{
				DarkModeTitleBar:           0x00131414,
				DarkModeTitleText:          0x00ececed,
				DarkModeBorder:             0x002f3234,
				DarkModeTitleBarInactive:   0x001c1e1f,
				DarkModeTitleTextInactive:  0x009b9c9c,
				DarkModeBorderInactive:     0x002f3234,
				LightModeTitleBar:          0x00e7e7e7,
				LightModeTitleText:         0x00141414,
				LightModeBorder:            0x00d4d4d4,
				LightModeTitleBarInactive:  0x00dedede,
				LightModeTitleTextInactive: 0x005c5c5c,
				LightModeBorderInactive:    0x00d4d4d4,
			},
		},
	})
	if err != nil {
		log.Fatalf("hibana: wails: %v", err)
	}
}

// updateLoop is the auto-update cadence ("app syncs with the internet and
// github"): the first check rides updateFirstDelay after boot (the board
// owns the wire first), then every updateEvery. Every check goes through
// the bridge's single-flight guard, so a manual modal round and the loop's
// round can never race; a refusal ("already running") is logged at debug,
// never an error. An unreachable GitHub is logged and RETRIED at the next
// tick — the app never claims "no update" when it simply could not ask.
func updateLoop(ctx context.Context, bridge *ui.API) {
	select {
	case <-ctx.Done():
		return
	case <-time.After(updateFirstDelay):
	}
	check := func() {
		res, err := bridge.CheckForUpdates()
		if err != nil {
			log.Printf("hibana update: check failed: %v", err)
			return
		}
		if res.Available {
			log.Printf("hibana update: %s is out (running %s) — the Update button is on the toolbar", res.Latest, res.Current)
		}
	}
	check()
	t := time.NewTicker(updateEvery)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			check()
		}
	}
}

// syncLoop is the pull cadence (§10): startup + every 5 minutes; each round
// refreshes the projects list, pulls every mirrored board (304s are one
// header), and drains the outbox when it has entries. A 401 anywhere in the
// round means the session died: the bridge is notified (the login card
// reopens); the next round after a re-login recovers on its own.
func syncLoop(ctx context.Context, engine *sync.Engine, bridge *ui.API) {
	round := func() {
		pulled, errs := engine.SyncOnce(ctx)
		for _, err := range errs {
			var se *api.StatusError
			if errors.As(err, &se) && se.Status == http.StatusUnauthorized {
				bridge.NotifyAuthLost("pull-401")
			}
			log.Printf("hibana sync: %v", err)
		}
		res, err := engine.Drain(ctx)
		if err != nil {
			log.Printf("hibana sync: drain: %v", err)
		}
		if res.Done > 0 || res.Dropped > 0 || res.Held > 0 {
			log.Printf("hibana sync: round done (boards pulled: %d, outbox done/dropped/held: %d/%d/%d)", pulled, res.Done, res.Dropped, res.Held)
		}
	}
	round() // startup pull
	t := time.NewTicker(pullEvery)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			round()
		}
	}
}

// resolveDataDir implements the never-mix data rule (WPP §1): portable mode
// is chosen by --portable OR a zero-byte portable.marker next to the exe →
// .\data\; otherwise the OS data dir (%LOCALAPPDATA%\hibana\ on Windows).
// The choice locks into mode.lock on first launch and the lock WINS on every
// later launch — the app never silently migrates between profiles.
func resolveDataDir() (string, error) {
	exe, err := os.Executable()
	if err != nil {
		return "", err
	}
	exeDir := filepath.Dir(exe)
	portableFlag := false
	for _, a := range os.Args[1:] {
		if a == "--portable" {
			portableFlag = true
		}
	}
	_, markerErr := os.Stat(filepath.Join(exeDir, "portable.marker"))
	portableNow := portableFlag || markerErr == nil

	osDir := os.UserConfigDir // %LOCALAPPDATA% on Windows, ~/.config elsewhere
	if runtime.GOOS == "windows" {
		// WPP §8: %LOCALAPPDATA%\hibana\ (the plan's canonical installed path).
		if la := os.Getenv("LOCALAPPDATA"); la != "" {
			osDir = func() (string, error) { return filepath.Join(la, appDirName), nil }
		}
	}

	installedDir := func() (string, error) {
		base, err := osDir()
		if err != nil {
			return "", err
		}
		if runtime.GOOS == "windows" {
			return filepath.Join(base, appDirName), nil
		}
		return filepath.Join(base, appDirName), nil
	}

	lockPath := ""
	candidate := ""
	if portableNow {
		candidate = filepath.Join(exeDir, "data")
		lockPath = filepath.Join(candidate, "mode.lock")
	} else {
		d, err := installedDir()
		if err != nil {
			return "", err
		}
		candidate = d
		lockPath = filepath.Join(candidate, "mode.lock")
	}
	if err := os.MkdirAll(candidate, 0o755); err != nil {
		return "", err
	}

	// The lock wins: a recorded choice is never silently overridden.
	if b, err := os.ReadFile(lockPath); err == nil {
		switch strings.TrimSpace(string(b)) {
		case "portable":
			return filepath.Join(exeDir, "data"), nil
		case "installed":
			return installedDir()
		}
	}
	mode := "installed"
	if portableNow {
		mode = "portable"
	}
	if err := os.WriteFile(lockPath, []byte(mode), 0o600); err != nil {
		return "", err
	}
	return candidate, nil
}
