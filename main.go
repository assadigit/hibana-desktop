// hibana-desktop — the Hibana Kanban Windows desktop port (ADR-001:
// Go + Wails v2 + WebView2 + modernc.org/sqlite; the decision record lives in
// hibana-source docs/project-kanban/GO-DESKTOP-IMPLEMENTATION-GUIDE.md §0).
//
// M1+M2 scope (this build): the Wails shell bootstrap, the embedded board
// island (frontend/dist — a checksum-pinned snapshot of hibana-source @
// WebRef), the bridge (internal/ui — the Request transport + the §5.5 login
// surface), the cloud client (internal/api), the SQLite mirror
// (internal/store), and the sync loop (internal/sync: pull with the ETag
// cheap-poll on startup/5-minute cadence; the outbox drain runs when the
// queue is non-empty).
//
// THE LOGIN-FIRST BOOT (guide §5.5, the M2 pick landed): a stored live
// session boots straight into the board; otherwise the island-rendered
// login card opens first (js/desktop-login.js + css/desktop-login.css,
// generated by the island sync) — sign in once against hibana.ir, the page
// reloads with a live session, the kanban loads. A 401 mid-session (island
// read, pull loop, or outbox drain) reopens the card via the
// hibana:auth-required event; a successful re-login wakes the outbox's
// retry-once and kicks a fresh sync round.
